#!/usr/bin/env bash
# Fail if the vendored contract JavaScript under src/lib/contracts/ differs from what eotha-contracts
# would generate today. Regenerates from a clean export of the contracts ref in a scratch directory;
# the sibling checkout is never modified.
#
#   CONTRACTS_DIR            eotha-contracts git checkout (default: ../eotha-contracts)
#   CONTRACTS_REF            ref to regenerate from (default: origin/main after a best-effort fetch, else HEAD)
#   CONTRACT_DRIFT_REQUIRE=1 fail instead of skipping when the checkout is absent (use in CI)
#
# Everything before the "// Code generated by" line (vendoring provenance comments) is ignored, whatever
# its length; relative import specifiers are compared after the same ".js" rewrite used when vendoring.
# The vendored set is the generated exploration binding plus the relative-import closure of penalty_delivery.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONTRACTS="${CONTRACTS_DIR:-$ROOT/../eotha-contracts}"
VENDOR="$ROOT/src/lib/contracts"

if [ ! -d "$CONTRACTS/.git" ] && ! git -C "$CONTRACTS" rev-parse --git-dir >/dev/null 2>&1; then
  if [ "${CONTRACT_DRIFT_REQUIRE:-0}" = 1 ]; then
    echo "contract-drift: $CONTRACTS is not a git checkout and CONTRACT_DRIFT_REQUIRE=1." >&2
    exit 1
  fi
  echo "contract-drift: $CONTRACTS not found; skipping (set CONTRACTS_DIR to override)." >&2
  exit 0
fi

REF="${CONTRACTS_REF:-}"
if [ -z "$REF" ]; then
  GIT_TERMINAL_PROMPT=0 git -C "$CONTRACTS" fetch --quiet origin main 2>/dev/null || echo "contract-drift: could not fetch origin/main; using local refs." >&2
  if git -C "$CONTRACTS" rev-parse --verify --quiet origin/main >/dev/null; then REF=origin/main; else REF=HEAD; fi
fi
SHA="$(git -C "$CONTRACTS" rev-parse --verify "$REF^{commit}")"

SCRATCH="$(mktemp -d)"
trap 'rm -rf "$SCRATCH"' EXIT
mkdir "$SCRATCH/src" "$SCRATCH/js"
git -C "$CONTRACTS" archive "$SHA" | tar -x -C "$SCRATCH/src"

echo "contract-drift: regenerating from eotha-contracts $REF ($SHA)"
(cd "$SCRATCH/src" && npm ci --silent && npm run --silent generate >/dev/null)

# shellcheck source=lib/contracts-lib.sh
. "$ROOT/scripts/lib/contracts-lib.sh"
TOOLS="$ROOT/scripts/lib/contracts-tools.mjs"
contracts_compile "$SCRATCH/src" "$SCRATCH/js"

status=0
drift() { echo "DRIFT: $*" >&2; status=1; }

compare() { # vendored-file generated-file
  local vendored="$1" generated="$2"
  if [ ! -f "$vendored" ]; then
    drift "${vendored#$ROOT/} is missing; eotha-contracts $REF generates it (re-vendor with scripts/sync-contracts.sh)"
  elif ! diff -u --label "vendored/${vendored#$VENDOR/}" --label "generated/${generated#$SCRATCH/js/}" \
    <(node "$TOOLS" body "$vendored") <(node "$TOOLS" body "$generated"); then
    drift "${vendored#$ROOT/} differs from eotha-contracts $REF"
  fi
}

# exploration.js is vendored standalone, so the generated file must not import anything relative.
exploration_files="$(node "$TOOLS" closure "$SCRATCH/js" "$CONTRACTS_EXPLORATION_ENTRY")"
if [ "$exploration_files" != "$CONTRACTS_EXPLORATION_ENTRY" ]; then
  drift "$CONTRACTS_EXPLORATION_ENTRY now imports other generated files ($(echo "$exploration_files" | tr '\n' ' ')); the standalone src/lib/contracts/exploration.js cannot hold them"
else
  compare "$VENDOR/exploration.js" "$SCRATCH/js/$CONTRACTS_EXPLORATION_ENTRY"
fi

# The penalty tree is the relative-import closure of penalty_delivery: every generated file in it must
# be vendored (a new transitive proto dependency is caught here), and nothing else may be.
expected="$(node "$TOOLS" closure "$SCRATCH/js" "$CONTRACTS_PENALTY_ENTRY")"
actual="$(cd "$VENDOR/penalty" && find . -name '*.js' | sed 's#^\./##' | sort)"
while IFS= read -r rel; do
  compare "$VENDOR/penalty/$rel" "$SCRATCH/js/$rel"
done <<< "$expected"
while IFS= read -r rel; do
  [ -z "$rel" ] || printf '%s\n' "$expected" | grep -qxF "$rel" \
    || drift "src/lib/contracts/penalty/$rel is vendored but eotha-contracts $REF no longer imports it from $CONTRACTS_PENALTY_ENTRY"
done <<< "$actual"

if [ "$status" -ne 0 ]; then
  echo "contract-drift: vendored contracts are out of date with eotha-contracts $REF ($SHA); run scripts/sync-contracts.sh." >&2
  exit 1
fi
echo "contract-drift: vendored contracts match eotha-contracts $REF ($SHA)."
